import { readFileSync, writeFileSync } from "node:fs";

const catalog = readFileSync(new URL("../icons/index.js", import.meta.url), "utf8");
const names = [...catalog.matchAll(/^\s*"([^"]+)": icon\d+/gm)].map(match => match[1]);
const componentName = name => "Icon" + name.split("-").map(part => part[0].toUpperCase() + part.slice(1)).join("");
const componentNames = names.map(componentName);
if (new Set(componentNames).size !== names.length) throw new Error("Duplicate icon component name");
const license = readFileSync(new URL("../src/components/ui/catalog-icon.tsx", import.meta.url), "utf8").split("import { forwardRef")[0];
const source = license + [
  "// Generated by scripts/build-icon-components.mjs from the public SVG catalog.",
  'import { createCatalogIcon } from "./catalog-icon";',
  "",
  ...names.flatMap(name => [
    `/** ${name} icon from the Clidey UX catalog. */`,
    `export const ${componentName(name)} = /* @__PURE__ */ createCatalogIcon(${JSON.stringify(name)});`,
  ]),
  "",
].join("\n");
writeFileSync(new URL("../src/components/ui/catalog-icons.ts", import.meta.url), source);
console.log(`Generated ${names.length} catalog icon components`);
