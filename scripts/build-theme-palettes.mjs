import {readdir, readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname, join, resolve} from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'src/themes/css');
const destination = join(root, 'themes/palettes.css');
const files = (await readdir(source)).filter(name => name.endsWith('.css')).sort();
const contents = await Promise.all(files.map(async name => `/* ${name} */\n${await readFile(join(source, name), 'utf8')}`));
await mkdir(dirname(destination), {recursive: true});
await writeFile(destination, `/* Shared Clidey Design palettes. Generated by scripts/build-theme-palettes.mjs. */\n${contents.join('\n')}`);
console.log(`Built ${files.length} theme palettes.`);
